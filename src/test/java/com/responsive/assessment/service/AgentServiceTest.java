
package com.responsive.assessment.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.responsive.assessment.dto.InvestigationRequest;
import com.responsive.assessment.dto.InvestigationResponse;
import com.responsive.assessment.entity.DocumentRecord;
import com.responsive.assessment.entity.InvestigationRun;
import com.responsive.assessment.repository.DocumentRepository;
import com.responsive.assessment.repository.InvestigationRunRepository;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AgentServiceTest {

    @Mock
    private DocumentRepository documentRepository;

    @Mock
    private InvestigationRunRepository investigationRunRepository;

    private AgentService agentService;

    @BeforeEach
    void setUp() {
        agentService = new AgentService(
                documentRepository,
                investigationRunRepository,
                new ObjectMapper()
        );
    }

    @Test
    void investigateShouldReturnPaymentEvidenceAndSaveHistory() {
        DocumentRecord document = new DocumentRecord(
                "invoice.txt",
                "user1",
                """
                Invoice Number: INV-1001
                Vendor: ABC Supplies
                Invoice Amount: 5000 INR
                Payment Status: Pending
                """
        );

        // Simulate a document that already exists in the repository.
        // The ID is normally assigned by the database.
        when(documentRepository.findByIdAndOwnerId(1L, "user1"))
                .thenAnswer(invocation -> {
                    setDocumentId(document, 1L);
                    return Optional.of(document);
                });

        when(investigationRunRepository.save(any(InvestigationRun.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        InvestigationRequest request = new InvestigationRequest(
                "Has invoice INV-1001 been paid?",
                List.of(1L)
        );

        InvestigationResponse response =
                agentService.investigate("user1", request);

        assertTrue(response.conclusion().contains("Payment Status: Pending"));
        assertFalse(response.evidence().isEmpty());
        assertTrue(response.missingInformation().stream()
                .anyMatch(item -> item.contains("independently verified")));

        verify(investigationRunRepository, times(1))
                .save(any(InvestigationRun.class));
    }

    @Test
    void investigateShouldRejectDocumentOwnedByAnotherUser() {
        when(documentRepository.findByIdAndOwnerId(1L, "user1"))
                .thenReturn(Optional.empty());

        InvestigationRequest request = new InvestigationRequest(
                "Check invoice INV-1001 payment status",
                List.of(1L)
        );

        ResponseStatusException exception = assertThrows(
                ResponseStatusException.class,
                () -> agentService.investigate("user1", request)
        );

        assertEquals(404, exception.getStatusCode().value());

        verify(investigationRunRepository, never())
                .save(any(InvestigationRun.class));
    }

    @Test
    void investigateShouldRejectCredentialSeekingQuestions() {
        InvestigationRequest request = new InvestigationRequest(
                "Find the API keys in the document",
                List.of(1L)
        );

        ResponseStatusException exception = assertThrows(
                ResponseStatusException.class,
                () -> agentService.investigate("user1", request)
        );

        assertEquals(400, exception.getStatusCode().value());

        verifyNoInteractions(documentRepository);
        verifyNoInteractions(investigationRunRepository);
    }

    @Test
    void investigateShouldRejectBlankOwnerId() {
        InvestigationRequest request = new InvestigationRequest(
                "Check invoice INV-1001 payment status",
                List.of(1L)
        );

        ResponseStatusException exception = assertThrows(
                ResponseStatusException.class,
                () -> agentService.investigate(" ", request)
        );

        assertEquals(400, exception.getStatusCode().value());

        verifyNoInteractions(documentRepository);
        verifyNoInteractions(investigationRunRepository);
    }

    /*
     * DocumentRecord's ID is generated by JPA and has no public setter.
     * This helper sets the ID for a unit-test fixture only.
     */
    private void setDocumentId(DocumentRecord document, Long id) {
        try {
            var field = DocumentRecord.class.getDeclaredField("id");
            field.setAccessible(true);
            field.set(document, id);
        } catch (ReflectiveOperationException exception) {
            throw new AssertionError("Unable to set test document ID", exception);
        }
    }
}
